local types = require("types")

local schema = [[CREATE TABLE mail_library (
    revision %s,
    kind TEXT NOT NULL CHECK (kind IN ('base', 'message', 'part')),
    name TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    html TEXT NOT NULL,
    text TEXT NOT NULL,
    subject TEXT,
    base TEXT,
    schema_json TEXT NOT NULL,
    samples_json TEXT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('created', 'customized')),
    origin TEXT,
    author TEXT NOT NULL,
    created_at %s NOT NULL,
    updated_at %s NOT NULL,
    UNIQUE (kind, name),
    CHECK ((kind = 'message') = (subject IS NOT NULL AND base IS NOT NULL)),
    CHECK ((subject IS NULL) = (base IS NULL)),
    CHECK ((state = 'customized') = (origin IS NOT NULL))
)%s]]

local function create(db: types.Executor, sqlite: boolean)
    local number_type = sqlite and "INTEGER" or "BIGINT"
    local identity = sqlite and "INTEGER PRIMARY KEY AUTOINCREMENT" or "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    local statements = {
        schema:format(identity, number_type, number_type, sqlite and " STRICT" or ""),
        "CREATE INDEX mail_library_state ON mail_library(state, kind, name)",
        "CREATE INDEX mail_library_base ON mail_library(base, name) WHERE kind = 'message'",
    }
    for _, statement in ipairs(statements) do
        local _, err = db:execute(statement)
        if err then error(err) end
    end
end

local function drop(db: types.Executor)
    local _, err = db:execute("DROP TABLE mail_library")
    if err then error(err) end
end

return require("migration").define(function()
    migration("02 mail library", function()
        database("sqlite", function()
            up(function(db: types.Executor) create(db, true) end)
            down(drop)
        end)
        database("postgres", function()
            up(function(db: types.Executor) create(db, false) end)
            down(drop)
        end)
    end)
end)
