local types = require("types")

local function add(db: types.Executor, sqlite: boolean)
    local int = sqlite and "INTEGER" or "BIGINT"
    local identity = sqlite and "INTEGER PRIMARY KEY AUTOINCREMENT" or "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    local strict = sqlite and " STRICT" or ""
    local statements = {
        ([[CREATE TABLE mail_asset_file (
            upload_id TEXT PRIMARY KEY NOT NULL,
            filename TEXT NOT NULL,
            content_type TEXT NOT NULL,
            size_bytes %s NOT NULL,
            width %s,
            height %s,
            due_at %s
        )%s]]):format(int, int, int, int, strict),
        "CREATE INDEX mail_asset_file_due ON mail_asset_file(due_at,upload_id) WHERE due_at IS NOT NULL",
        ([[CREATE TABLE mail_library_asset (
            revision %s,
            name TEXT NOT NULL UNIQUE,
            title TEXT NOT NULL,
            description TEXT NOT NULL,
            origin TEXT,
            author TEXT NOT NULL,
            created_at %s NOT NULL,
            updated_at %s NOT NULL,
            upload_id TEXT REFERENCES mail_asset_file(upload_id)
        )%s]]):format(identity, int, int, strict),
        "CREATE INDEX mail_library_asset_upload ON mail_library_asset(upload_id)",
        "ALTER TABLE mail_library_revision ADD COLUMN asset_upload_id TEXT REFERENCES mail_asset_file(upload_id)",
        "CREATE INDEX mail_library_revision_asset ON mail_library_revision(asset_upload_id) WHERE asset_upload_id IS NOT NULL",
        [[CREATE TABLE mail_message_asset (
            message_id TEXT NOT NULL REFERENCES mail_message(id) ON DELETE CASCADE,
            name TEXT NOT NULL,
            content_id TEXT NOT NULL,
            original TEXT,
            upload_id TEXT REFERENCES mail_asset_file(upload_id),
            PRIMARY KEY (message_id,name),
            CHECK ((original IS NULL) <> (upload_id IS NULL))
        )]] .. strict,
        "CREATE INDEX mail_message_asset_upload ON mail_message_asset(upload_id) WHERE upload_id IS NOT NULL",
    }
    for _, statement in ipairs(statements) do
        local _, err = db:execute(statement)
        if err then error(err) end
    end
end

return require("migration").define(function()
    migration("07 mail library assets", function()
        database("sqlite", function() up(function(db: types.Executor) add(db, true) end) end)
        database("postgres", function() up(function(db: types.Executor) add(db, false) end) end)
    end)
end)
