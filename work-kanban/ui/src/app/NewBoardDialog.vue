<script setup lang="ts">
import { Icon } from '@iconify/vue'
import { latestRequest } from '@kickside/ui-kit/latestRequest'
import Button from 'primevue/button'
import Dialog from 'primevue/dialog'
import InputText from 'primevue/inputtext'
import { computed, ref, shallowRef, useId, watch } from 'vue'
import type { WorkClient } from '../work/client'
import { workFailure } from '../work/errors'
import { BoardCreation, type BoardCreationReadiness } from './newBoard'

const props = defineProps<{ visible: boolean, work: Pick<WorkClient, 'packs' | 'createBoard'> }>()
const emit = defineEmits<{ 'update:visible': [value: boolean], created: [board: string] }>()
const id = useId()
const title = ref('')
const prefix = ref('')
const loading = ref(false)
const saving = ref(false)
const uncertain = ref(false)
const readiness = shallowRef<BoardCreationReadiness>()
const catalogFailure = shallowRef<ReturnType<typeof workFailure>>()
const createFailure = shallowRef<ReturnType<typeof workFailure>>()
const begin = latestRequest()
const creation = new BoardCreation(props.work.createBoard, () => crypto.randomUUID())
const validPrefix = computed(() => !prefix.value.trim() || /^[A-Z][A-Z0-9]{1,9}$/.test(prefix.value.trim()))

async function loadCatalog() {
  const current = begin()
  loading.value = true
  readiness.value = undefined
  catalogFailure.value = undefined
  try {
    const catalog = await props.work.packs()
    if (current()) readiness.value = creation.configure(catalog)
  } catch (error) {
    if (current()) catalogFailure.value = workFailure(error)
  } finally {
    if (current()) loading.value = false
  }
}

watch(() => props.visible, visible => {
  if (visible) void loadCatalog()
  else begin()
})

async function submit() {
  if (saving.value || (!uncertain.value && (!readiness.value?.enabled || !validPrefix.value))) return
  saving.value = true
  createFailure.value = undefined
  try {
    const board = await creation.submit(title.value, prefix.value)
    if (!board) return
    title.value = ''
    prefix.value = ''
    emit('update:visible', false)
    emit('created', board.board_id)
  } catch (error) {
    createFailure.value = workFailure(error)
  } finally {
    uncertain.value = creation.awaitingConfirmation
    saving.value = false
  }
}
</script>

<template>
  <Dialog
    :visible="visible" modal append-to="self" :draggable="false"
    :closable="!saving" :close-on-escape="!saving" :aria-labelledby="id + '-heading'"
    class="kanban-new-board"
    @update:visible="emit('update:visible', $event)"
  >
    <template #header>
      <div class="kanban-modal-heading">
        <span class="kx-modal-head-icon"><Icon icon="tabler:plus" aria-hidden="true" /></span>
        <span class="kx-modal-head-text"><span :id="id + '-heading'" class="kx-modal-head-title">New board</span></span>
      </div>
    </template>
    <form :id="id + '-form'" class="kanban-board-form" @submit.prevent="submit">
      <div class="kanban-board-field">
        <label :for="id + '-name'">Board name</label>
        <InputText :id="id + '-name'" v-model="title" required maxlength="255" autofocus :disabled="saving || uncertain" />
      </div>
      <div class="kanban-board-field">
        <label :for="id + '-prefix'">Key prefix (optional)</label>
        <InputText
          :id="id + '-prefix'" v-model="prefix" placeholder="Generated by Work" maxlength="10"
          :invalid="!validPrefix" :aria-describedby="!validPrefix ? id + '-prefix-error' : undefined"
          :disabled="saving || uncertain"
        />
        <small v-if="!validPrefix" :id="id + '-prefix-error'">
          Use 2–10 uppercase letters or digits, starting with a letter.
        </small>
      </div>
      <p v-if="loading" role="status">Checking the Kanban pack…</p>
      <p v-else-if="readiness?.pack">{{ readiness.pack.title }} · {{ readiness.pack.version }}</p>
      <p v-if="readiness?.message" role="status">{{ readiness.message }}</p>
      <div v-if="catalogFailure" role="alert">
        {{ catalogFailure.message }}
        <Button type="button" size="small" text label="Retry" @click="loadCatalog" />
      </div>
      <div v-if="createFailure" role="alert">
        <p>{{ createFailure.message }}</p>
        <small v-if="createFailure.code">{{ createFailure.code }}</small>
      </div>
    </form>
    <template #footer>
      <Button label="Cancel" severity="secondary" outlined :disabled="saving" @click="emit('update:visible', false)" />
      <Button
        type="submit" :form="id + '-form'" :label="uncertain ? 'Retry creation' : 'Create board'"
        :loading="saving" :disabled="!uncertain && (!title.trim() || !validPrefix || !readiness?.enabled)"
      />
    </template>
  </Dialog>
</template>
