local test = require("test")
local fixture = require("fixture")
local client = require("client")
local requests = require("requests")
local function define()
    test.describe("contract availability vocabulary", function()
        test.it("classifies a missing parsing contract as unavailable", function()
            fixture.set("missing")
            local err = requests.parse("get", {})
            test.eq(err:kind(), errors.UNAVAILABLE)
            test.eq(err:details().code, "contract_unavailable")
            test.is_true(err:retryable())
        end)
        test.it("classifies a malformed declared schema as an internal contract failure", function()
            fixture.set("bad_schema")
            local err = requests.parse("get", {})
            test.eq(err:kind(), errors.INTERNAL)
            test.eq(err:details().code, "contract_schema_invalid")
            test.is_false(err:retryable())
        end)
        for _, mode in ipairs({ "missing", "empty_client" }) do
            test.it("classifies " .. mode .. " as an unavailable contract", function()
                fixture.set(mode)
                local value, err = client.open()
                test.is_nil(value)
                test.eq(err:kind(), errors.UNAVAILABLE)
                test.eq(err:details().code, "contract_unavailable")
                test.is_true(err:retryable())
            end)
        end
    end)
end
return { run = test.run_cases(define) }
