local test=require("test")
local fixture=require("fixture")
local lifecycle=require("lifecycle")
local projection_state=require("projection_state")
local attachments=require("attachments")
local function define()
    test.describe("lifecycle audit",function()
        test.it("writes nothing while ensuring an unchanged attachment",function()
            fixture.reset("unchanged")
            local id,created,err=attachments.ensure("catalog","plugin",2,"kind","Plugin",{})
            test.is_nil(err,tostring(err))
            test.is_true(id~=nil)
            test.is_false(created)
            test.eq(fixture.writes(),0)
            assert(attachments.ensure("catalog","plugin",2,"kind","Plugin",{changed=true}))
            test.eq(fixture.writes(),1,"changed configuration still patches the attachment")
        end)
        test.it("writes nothing while reconciling unchanged ready plugin state",function()
            fixture.reset("unchanged")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(err,tostring(err))
            test.is_true(out.done)
            test.eq(fixture.writes(),0)
            local _,registered,rebuilt=fixture.counts()
            test.eq(registered+rebuilt,0)
        end)
        test.it("resets projections when only the configuration start sequence changes",function()
            fixture.reset("new_sequence")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(err,tostring(err))
            test.is_true(out.done)
            local _,registered=fixture.counts()
            test.eq(registered,1)
        end)
        test.it("withholds projection progress from another declared revision",function()
            fixture.reset("state_revision")
            local plugin=assert(fixture.load("a"))
            local progress,err=projection_state.states("catalog",plugin,fixture.state())
            test.is_nil(err,tostring(err))
            test.is_nil(progress.fold)
        end)
        test.it("surfaces catalog read cleanup failures before lifecycle work",function()
            fixture.reset("release_failure")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(out)
            test.eq(err:details().code,"lifecycle_release_failed")
            local removed,ensured,rebuilt=fixture.counts()
            test.eq(removed+ensured+rebuilt,0)
        end)
        test.it("returns native retryable failures while keeping lifecycle pending",function()
            fixture.reset("transient")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(out)
            test.eq(err:kind(),errors.UNAVAILABLE)
            test.eq(err:details().code,"attachment_offline")
            test.is_true(err:retryable())
            test.eq(fixture.state().lifecycle.state,"pending")
        end)
        test.it("isolates deterministic failures",function()
            fixture.reset("deterministic")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(err)
            test.is_true(out.done)
            test.eq(fixture.state().lifecycle.state,"failed")
        end)
        test.it("removes inactive resources without a loadable manifest",function()
            fixture.reset("missing")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(err)
            test.is_true(out.done)
            test.eq(fixture.counts(),1)
        end)
        test.it("resets projections for a new attachment with unchanged config",function()
            fixture.reset("new_activation")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(err,tostring(err))
            test.is_true(out.done)
            local _,registered=fixture.counts()
            test.eq(registered,1)
        end)
        test.it("reconciles ready plugins after revision changes",function()
            fixture.reset("revision")
            local out,err=lifecycle.batch({catalog_id="catalog"})
            test.is_nil(err,tostring(err))
            test.is_false(out.done)
            local _,_,rebuilt=fixture.counts()
            test.eq(rebuilt,1)
        end)
    end)
end
return {run=test.run_cases(define)}
