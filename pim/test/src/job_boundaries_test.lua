local test = require("test")
local fixture = require("job_fixture")
local merge = require("merge")
local clock = require("clock")
local scoped = require("scoped")
local catalog_fixture = require("catalog_fixture")
local store = require("store")

type JobInput = { job: { id: string, lease_token: string, execution_seq: integer, deadline: string }, payload: { catalog_id: string, vocabulary: string, from: string } }
local function input(deadline: string): JobInput
    return { job = { id = "job", lease_token = "lease", execution_seq = 1, deadline = deadline },
        payload = { catalog_id = "catalog", vocabulary = "v", from = "a" } }
end
local function define()
    test.describe("job execution boundaries", function()
        test.it("requires ADMIN before a direct rebuild batch changes catalog state", function()
            local h = scoped.catalog(scoped.member())
            catalog_fixture.boot(h)
            local reader = scoped.member()
            assert(h.call("grant", { subject_id = reader.id, mask = 1 }))
            local db = assert(store.open())
            assert(db:execute("UPDATE kickside_pim_catalog SET rebuild_after = '', rebuild_seq = applied_seq WHERE catalog_id = $1", { h.id }))
            db:release()
            local out, err = reader.call("rebuild_batch", { deadline = "2090-01-01T00:00:00Z" }, h.id)
            local read = assert(store.open())
            local after = assert(store.catalog(read, h.id)).rebuild_after
            assert(read:execute("UPDATE kickside_pim_catalog SET rebuild_after = NULL, rebuild_seq = NULL WHERE catalog_id = $1", { h.id }))
            read:release()
            test.is_nil(out)
            test.eq(err:kind(), errors.PERMISSION_DENIED)
            test.eq(after, "")
        end)

        test.it("rearms before starting a command outside the enclosing budget", function()
            fixture.reset(nil)
            local result, err = merge.run(input(clock.now()))
            test.is_nil(err, tostring(err))
            test.eq(fixture.calls, 0)
            test.eq(fixture.completed, 1)
            test.is_true(result.self_completed)
        end)
        test.it("passes the enclosing deadline to the command batch", function()
            fixture.reset(nil)
            local deadline = clock.offset(60)
            local result, err = merge.run(input(deadline))
            test.is_nil(err, tostring(err))
            test.eq(fixture.calls, 1)
            test.eq(fixture.request.deadline, deadline)
            test.is_true(result.merged)
        end)
        test.it("propagates a native database release failure before issuing work", function()
            fixture.reset(nil, errors.new({ kind = errors.UNAVAILABLE, retryable = true, message = "pool release fails", details = { code = "pool_release" } }))
            local result, err = merge.run(input(clock.offset(60)))
            test.is_nil(result)
            test.eq(err:kind(), errors.UNAVAILABLE)
            test.eq(err:details().code, "pool_release")
            test.eq(fixture.calls, 0)
        end)

        test.it("returns a batch's native error with its fields intact", function()
            fixture.reset(errors.new({ kind = errors.PERMISSION_DENIED, retryable = false, message = "batch refuses access", details = { code = "batch_denied", actor = "actor" } }))
            local result, err = merge.run(input(clock.offset(60)))
            test.is_nil(result)
            test.eq(err:kind(), errors.PERMISSION_DENIED)
            test.is_false(err:retryable())
            test.eq(err:details().code, "batch_denied")
            test.eq(err:details().actor, "actor")
        end)
    end)
end
return { run = test.run_cases(define) }
