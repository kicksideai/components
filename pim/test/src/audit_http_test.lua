local test=require("test")
local fixture=require("fixture")
local api=require("api")
local function define()
    test.describe("HTTP admission audit",function()
        test.it("bounds raw whitespace while reading before decoding or contract work",function()
            fixture.reset(string.rep(" ",4194305).."{}",nil)
            api.command("apply")
            local out=fixture.result()
            test.eq(out.max_body,4194304)
            test.eq(out.calls,0)
            test.eq(out.status,400)
        end)
        test.it("returns body read failures without invoking the contract",function()
            fixture.reset("",errors.new({kind=errors.INVALID,retryable=false,message="read failed",details={code="body_read_failed",probe=true}}))
            api.command("apply")
            local out=fixture.result()
            test.eq(out.calls,0)
            test.eq(out.status,400)
            test.eq((out.payload :: {[string]:unknown}).details.code,"body_read_failed")
        end)
    end)
end
return {run=test.run_cases(define)}
