            test.is_nil(plan:find("TEMP B-TREE",1,true),plan)
        end)
        test.it("prunes expired receipts proposals and completed release work in bounded pages",function()
            local h=fixture.catalog()
            local db=assert(store.open())
            local tx=assert(db:begin())
            for n=1,510 do
                assert(tx:execute([[INSERT INTO kickside_pim_receipt(catalog_id,marker,request_hash,result,first_seq,event_count,noop,expires_at)
                    VALUES($1,$2,'hash','{}',1,1,1,'2000-01-01T00:00:00Z')]],{h.id,"old-"..n}))
                assert(tx:execute([[INSERT INTO kickside_pim_proposal(catalog_id,proposal_id,origin,items,base,status,created_by,created_at) VALUES($1,$2,'{}','[]','{"generation":1,"versions":{}}','rejected','reader','2000-01-01T00:00:00Z')]],{h.id,"old-"..n}))
                assert(tx:execute([[INSERT INTO kickside_pim_release_job(catalog_id,request_id,model_id,root,identity,job_id,after_product,done,completed_at) VALUES($1,$2,'model',1,'{}','job','',1,'2000-01-01T00:00:00Z')]],{h.id,"old-"..n}))
