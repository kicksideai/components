    test.describe("audit regressions", function()
        test.it("continues when retiring an expired child makes its parent collectable",function()
            local h=fixture.catalog()
            assert(h.call("apply_schema",{declaration={policy={audit_days=1}}}))
            local out=assert(h.call("apply",{items={
                {term={vocabulary="categories",code="a-old-parent"},labels={en="Parent"}},
                {term={vocabulary="categories",code="z-old-child"},labels={en="Child"},parent="a-old-parent"},
                {term={vocabulary="categories",code="z-old-child"},retired=true},
                {term={vocabulary="categories",code="a-old-parent"},retired=true}
            }}))
            test.is_true(out.applied,json.encode(out))
            local db=assert(store.open())
            assert(db:execute("UPDATE kickside_pim_term SET retired_at='2000-01-01T00:00:00Z' WHERE catalog_id=$1 AND retired=1",{h.id}))
            assert(db:release())
            assert(fixture.retain())
            local read=assert(store.open())
            local rows=assert(read:query("SELECT code FROM kickside_pim_term WHERE catalog_id=$1 AND retired=1",{h.id}))
            assert(read:release())
            test.eq(#rows,0,"removing a protection must schedule its newly eligible dependent")
        end)
        test.it("ages unreferenced storage while preserving current publications and generations",function()
            local h=fixture.catalog()
            fixture.boot(h)
            assert(h.call("apply_schema",{declaration={channels={{id="other",requirements={"web"}}}}}))
            local function release(channel:string): string
                local p=assert(h.call("get",{product={sku="RDG-moss-40"}})).product
                local result=assert(h.call("release",{items={{product={id=p.product_id},expect_version=p.version,channels={channel}}}})).outcomes[1]
                assert(result.release_id,json.encode(result))
                return result.release_id
            end
            local first=release("web")
            assert(h.call("apply",{items={{product={sku="RDG"},expect_version="any",set={{attr="core.care",value="second"}}}}}))
            local protected=release("other")
            assert(h.call("apply",{items={{product={sku="RDG"},expect_version="any",set={{attr="core.care",value="third"}}}}}))
            local current=release("web")
            assert(h.call("apply_schema",{declaration={policy={audit_days=1}}}))
            local db=assert(store.open())
            assert(db:execute("UPDATE kickside_pim_release SET created_at='2000-01-01T00:00:00Z' WHERE catalog_id=$1",{h.id}))
            for n=1,510 do
                assert(db:execute([[WITH source AS (SELECT * FROM kickside_pim_release WHERE catalog_id=$1 AND release_id=$2) INSERT INTO kickside_pim_release(catalog_id,release_id,product_id,version,generation,snapshot,hash,channels,seq,created_at)
                    SELECT catalog_id,$3,product_id,version,generation,snapshot,hash,channels,seq,created_at FROM source]],{h.id,first,"old-"..n}))
            end
            -- More protected releases than a catalog's full page must not
            -- hide the superseded releases following them in the age keyset.
            for n=1,60 do
                local kept="0-protected-"..n
                assert(db:execute([[WITH source AS (SELECT * FROM kickside_pim_release WHERE catalog_id=$1 AND release_id=$2)
                    INSERT INTO kickside_pim_release(catalog_id,release_id,product_id,version,generation,snapshot,hash,channels,seq,created_at)
                    SELECT catalog_id,$3,product_id,version,generation,snapshot,hash,channels,seq,created_at FROM source]],{h.id,first,kept}))
                assert(db:execute([[WITH source AS (SELECT * FROM kickside_pim_release WHERE catalog_id=$1 AND release_id=$2)
                    INSERT INTO kickside_pim_publication(catalog_id,channel,product_id,release_id,state,seq,updated_at)
                    SELECT catalog_id,$3,product_id,release_id,'published',seq,created_at FROM source]],{h.id,kept,"protected-"..n}))
            end
            assert(db:execute([[INSERT INTO kickside_pim_publication(catalog_id,channel,product_id,release_id,state,seq,updated_at)
                VALUES($1,'web','old-product',$2,'withdrawn',1,'2000-01-01T00:00:00Z')]],{h.id,first}))
            assert(db:execute([[INSERT INTO kickside_pim_generation(catalog_id,generation,declaration,compiled,digest,class,actor,applied_seq,applied_at)
                SELECT catalog_id,999,declaration,compiled,digest,class,actor,applied_seq,'2000-01-01T00:00:00Z' FROM kickside_pim_generation WHERE catalog_id=$1 AND generation=1]],{h.id}))
            assert(db:execute("UPDATE kickside_pim_generation SET applied_at='2000-01-01T00:00:00Z' WHERE catalog_id=$1",{h.id}))
            assert(db:execute("INSERT INTO kickside_pim_attribute_usage(catalog_id,attribute_id,products) VALUES($1,999,0)",{h.id}))
            assert(h.call("apply",{items={{term={vocabulary="categories",code="old-retired"},labels={en="Old"},retired=true}}}))
            -- Age through the owned term timestamp once that column exists.
            local columns=assert(db:query("SELECT * FROM kickside_pim_term WHERE catalog_id=$1 AND code='old-retired'",{h.id}))
            if columns[1].retired_at~=nil then assert(db:execute("UPDATE kickside_pim_term SET retired_at='2000-01-01T00:00:00Z' WHERE catalog_id=$1 AND code='old-retired'",{h.id})) end
            assert(db:execute("UPDATE kickside_pim_retention SET catalog_id='',inclusive=0,product_after='',deadline_ms=NULL WHERE owner_id='pim'",{}))
            for _=1,100 do
                local out=assert(funcs.call("kickside.pim.retention:owner",{}))
                test.is_true(out.success,tostring(out.error));test.is_true(out.deleted<=500)
                if not out.needs_continue then break end
            end
            local releases=assert(db:query("SELECT release_id FROM kickside_pim_release WHERE catalog_id=$1 ORDER BY release_id",{h.id}))
            local generations=assert(db:query("SELECT generation FROM kickside_pim_generation WHERE catalog_id=$1 AND generation=999",{h.id}))
            local usage=assert(db:query("SELECT * FROM kickside_pim_attribute_usage WHERE catalog_id=$1 AND attribute_id=999",{h.id}))
            local terms=assert(db:query("SELECT * FROM kickside_pim_term WHERE catalog_id=$1 AND code='old-retired'",{h.id}))
            local tombs=assert(db:query("SELECT * FROM kickside_pim_publication WHERE catalog_id=$1 AND state<>'published'",{h.id}))
            assert(db:release())
            test.eq(#releases,62)
            local kept={};for _,r in ipairs(releases) do kept[r.release_id]=true end
            test.is_true(kept[protected]);test.is_true(kept[current])
            test.eq(#generations,0);test.eq(#usage,0);test.eq(#terms,0);test.eq(#tombs,0)
        end)
