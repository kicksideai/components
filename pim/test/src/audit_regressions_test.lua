            local left=assert(read:query("SELECT COUNT(*) AS n FROM kickside_pim_release_job WHERE catalog_id=$1",{h.id}))[1].n
            local proposals=assert(read:query("SELECT COUNT(*) AS n FROM kickside_pim_proposal WHERE catalog_id=$1",{h.id}))[1].n
            assert(read:release())
            test.eq(tonumber(left),0)
            test.eq(tonumber(proposals),0)
            test.is_true(removed>=1530)
        end)
