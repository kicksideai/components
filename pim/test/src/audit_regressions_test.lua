        test.it("reports blocked catalogs while preserving healthy retention continuation",function()
            local h=fixture.catalog()
            local db=assert(store.open())
            local current=assert(store.catalog(db,h.id))
            for n=1,12 do
                assert(db:execute([[INSERT INTO kickside_pim_catalog(catalog_id,generation,compiled,digest,layout_digest,item_table,applied_seq,product_count,item_count,trashed_count,tombstone_floor_seq,created_at,updated_at)
                    VALUES($1,1,$2,'d','d',$3,0,0,0,0,0,'2000','2000')]],{string.format("zz-audit-blocked-%02d",n),n==1 and "broken" or json.encode(current.compiled),current.item_table}))
            end
            assert(db:execute("UPDATE kickside_pim_retention SET catalog_id='zz-audit-blocked-',inclusive=0,product_after=''",{}))
            assert(db:release())
            local out,err=funcs.call("kickside.pim.retention:owner",{})
            local clean=assert(store.open())
            assert(clean:execute("DELETE FROM kickside_pim_catalog WHERE catalog_id LIKE 'zz-audit-blocked-%'",{}))
            assert(clean:execute("UPDATE kickside_pim_retention SET catalog_id='',inclusive=0,product_after=''",{}))
            assert(clean:release())
            test.is_nil(err,tostring(err))
            test.is_true(out.success,tostring(out.error))
            test.is_true(out.needs_continue)
