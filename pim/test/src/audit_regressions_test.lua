        test.it("uses the retention keyset index without sorting the trash backlog",function()
            local h=fixture.catalog()
            local db=assert(store.open())
            if db:type()~="sqlite" then assert(db:release()); return end
            local plan=""
            local executor={query=function(_self: unknown,statement: string,args: types.SqlParams): (unknown,error?)
                for _,row in ipairs(assert(db:query("EXPLAIN QUERY PLAN "..statement,args))) do plan=plan..tostring(row.detail) end
                return db:query(statement,args)
            end} :: types.Executor
            local _,err=retention_rows.trashed(executor,h.id,"2099-01-01T00:00:00Z",10,"")
