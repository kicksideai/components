        test.it("advances healthy cleanup past a blocked cleanup component",function()
            local bad=fixture.catalog()
            local healthy=fixture.catalog()
            local db=assert(store.open())
            local kept=assert(db:query("SELECT compiled FROM kickside_pim_catalog WHERE catalog_id=$1",{bad.id}))[1].compiled
            assert(db:execute("UPDATE kickside_pim_catalog SET compiled='broken' WHERE catalog_id=$1",{bad.id}))
            assert(db:execute("INSERT INTO kickside_pim_cleanup(catalog_id,cleaned,attempted_at) VALUES($1,0,''),($2,0,'1')",{bad.id,healthy.id}))
            assert(db:release())
            local out,err=funcs.call("kickside.pim.retention:owner",{})
            local read=assert(store.open())
            local remains=store.catalog(read,healthy.id)
            assert(read:execute("UPDATE kickside_pim_catalog SET compiled=$1 WHERE catalog_id=$2",{kept,bad.id}))
            assert(read:execute("DELETE FROM kickside_pim_cleanup WHERE catalog_id IN ($1,$2)",{bad.id,healthy.id}))
            assert(read:release())
            test.is_nil(err,tostring(err))
            test.is_true(out.success)
            test.eq(out.blocked[1].component_id,bad.id)
            test.is_nil(remains)
        end)
        test.it("rejects an incomplete tool through normalized catalog admission",function()
