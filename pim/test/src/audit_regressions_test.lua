            assert(tx:commit()); assert(db:release())
            local removed=0
            for _=1,200 do
                local out=assert(funcs.call("kickside.pim.retention:owner",{}))
                test.is_true(out.success,tostring(out.error))
                test.is_true(out.deleted<=500)
                removed=removed+out.deleted
                if not out.needs_continue then break end
