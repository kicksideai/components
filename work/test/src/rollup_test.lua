local test = require("test")
local fixture = require("fixture")
local steps = require("steps")
local store = require("store")

type Map = { [string]: unknown }

local declaration = require("rollup_fixture").declaration

local function values(h: fixture.Handle, id: string): Map
    return (assert(steps.get(h, id)).item :: Map).values :: Map
end

local function define()
    test.describe("rollups", function()
        test.it("stores aggregate values through apply and read and preserves parent version and history", function()
            local h = fixture.board({ declaration = declaration() })
            local p = steps.create(h, "parent")
            test.eq(values(h, p).count, 0)
            local version = steps.version(h, p)
            local a = steps.create(h, "child", { points = 2, cost = "0.1", title = "A", due = "2026-01-01T00:00:00Z", priority = "high" }, p)
            local b = steps.create(h, "child", { points = 5, cost = "0.2", title = "B", due = "2026-02-01T00:00:00Z", priority = "low" }, p)
            local v = values(h, p)
            test.eq(v.count, 2); test.eq(v.total, 7); test.eq(v.costs, "0.3")
            test.eq(v.minimum, 2); test.eq(v.maximum, 5); test.eq(v.average, "3.5")
            test.eq(v.first, "2026-01-01T00:00:00.000000000Z"); test.eq(v.last, "2026-02-01T00:00:00.000000000Z")
            test.eq(v.recent, "B"); test.eq(v.ranked, "B")
            test.eq(steps.version(h, p), version)
            test.eq(#assert(h.call("list_history", { item = { id = p } })).entries, 1)
            test.eq(steps.one(h, { op = "transition", item = a, transition = "finish" }).status, "applied")
            test.eq(values(h, p).done, "50")
            test.eq(steps.one(h, { op = "transition", item = b, transition = "cancel" }).status, "applied")
            test.eq(values(h, p).done, "100")
            steps.one(h, { op = "rank", item = a, after = b })
            test.eq(values(h, p).ranked, "A"); test.eq(values(h, p).recent, "B")
            steps.one(h, { op = "set", item = a, values = { points = 9 } })
            test.eq(values(h, p).total, 14)
            local db = assert(store.open())
            local board = assert(store.board(db, h.id))
            local usage = assert(store.usage(db, h.id))
            test.eq(usage.fields[board.model.fields.total.id], 1)
            db:release()
        end)

        test.it("keeps decimal cancellation and repeating averages exact within the value form", function()
            local d = declaration()
            local fields = d.fields :: { Map }
            fields[11].field = "cost"
            local h = fixture.board({ declaration = d })
            local p = steps.create(h, "parent")
            test.is_nil(values(h, p).average)
            steps.create(h, "child", { cost = "10000.1" }, p)
            steps.create(h, "child", { cost = "-0.1" }, p)
            steps.create(h, "child", { cost = "0" }, p)
            test.eq(values(h, p).costs, "10000")
            test.eq(values(h, p).average, "3333.33333333333")
        end)

        test.it("orders dates and fractional UTC instants chronologically", function()
            local h = fixture.board({ declaration = declaration() })
            local p = steps.create(h, "parent")
            steps.create(h, "child", { due = "2026-01-01T00:00:00Z" }, p)
            steps.create(h, "child", { due = "2026-01-01T00:00:00.1Z" }, p)
            test.eq(values(h, p).first, "2026-01-01T00:00:00.000000000Z")
            test.eq(values(h, p).last, "2026-01-01T00:00:00.100000000Z")
            steps.create(h, "child", { due = "2025-12-31" }, p)
            test.eq(values(h, p).first, "2025-12-31")
        end)

        test.it("refuses set clear unset and create writes with read_only", function()
            local h = fixture.board({ declaration = declaration() })
            local p = steps.create(h, "parent")
            for _, op in ipairs({ { op = "set", item = p, values = { total = 1 } }, { op = "set", item = p, clear = { "total" } },
                { op = "set", item = p, unset = { "total" } }, { op = "create", type = "parent", values = { total = 1 } } }) do
                local out = steps.one(h, op)
                test.eq(out.status, "invalid"); test.eq((out.findings :: { Map })[1].code, "read_only")
            end
        end)

        test.it("updates old and new parents and excludes trash across restore and relations", function()
            local h = fixture.board({ declaration = declaration() })
            local p, q = steps.create(h, "parent"), steps.create(h, "parent")
            local a = steps.create(h, "child", { points = 4 }, p)
            steps.one(h, { op = "parent", item = a, parent = q })
            test.eq(values(h, p).count, 0); test.eq(values(h, q).total, 4)
            steps.one(h, { op = "link", item = p, type = "blocks", target = { item = a } })
            steps.one(h, { op = "link", item = p, type = "relates", target = { item = a } })
            test.eq(values(h, p).related, 4); test.eq(values(h, a).symmetric, 1)
            steps.one(h, { op = "delete", item = a })
            test.eq(values(h, q).count, 0); test.eq(values(h, p).related, 0)
            steps.one(h, { op = "restore", item = a })
            test.eq(values(h, q).count, 1); test.eq(values(h, p).related, 4)
            steps.one(h, { op = "delete", item = q })
            test.eq(values(h, p).related, 0)
            steps.one(h, { op = "restore", item = q })
            test.eq(values(h, q).count, 1); test.eq(values(h, p).related, 4)
            steps.one(h, { op = "unlink", item = p, type = "blocks", target = { item = a } })
            test.eq(values(h, p).related, 0)
            local other = fixture.board({ declaration = declaration() })
            local remote = steps.create(other, "child", { points = 90 })
            steps.one(h, { op = "link", item = p, type = "blocks", target = { board = other.id, item = remote } })
            test.eq(values(h, p).related, 0)
        end)

        test.it("keeps a large sum exact", function()
            local h = fixture.board({ declaration = declaration() })
            local p = steps.create(h, "parent")
            steps.create(h, "child", { points = 9007199254740990 }, p)
            steps.create(h, "child", { points = 1 }, p)
            test.eq(values(h, p).total, 9007199254740991)
        end)

        test.it("holds no value for a sum outside the form's range and keeps folding", function()
            local h = fixture.board({ declaration = declaration() })
            local p = steps.create(h, "parent")
            local a = steps.create(h, "child", { points = 9007199254740991, cost = "999999999999999" }, p)
            steps.create(h, "child", { points = 9007199254740991, cost = "999999999999999" }, p)
            test.is_nil(values(h, p).total)
            test.is_nil(values(h, p).costs)
            test.eq(values(h, p).count, 2)
            local other = steps.one(h, { op = "set", item = a, values = { points = 0 } })
            test.eq(other.status, "applied")
            test.eq(values(h, p).total, 9007199254740991)
        end)

        test.it("refuses a link past the bound of a relation rollup and counts both ends of a symmetric one", function()
            local h = fixture.board({ declaration = declaration() })
            local p = steps.create(h, "parent")
            local a, b = steps.create(h, "child"), steps.create(h, "child")
            local db = assert(store.open())
            assert(db:execute([[WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 2000)
                INSERT INTO kickside_work_link (board_id, from_id, type, to_board_id, to_id, at, seq)
                SELECT $1, $2, 'blocks', $1, 'seeded-' || CAST(n.i AS text), 'now', 1 FROM n]], { h.id, p }))
            assert(db:execute([[WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 2000)
                INSERT INTO kickside_work_link (board_id, from_id, type, to_board_id, to_id, at, seq)
                SELECT $1, 'seeded-' || CAST(n.i AS text), 'relates', $1, $2, 'now', 1 FROM n]], { h.id, b }))
            db:release()
            local over = steps.one(h, { op = "link", item = p, type = "blocks", target = { item = a } })
            test.eq(over.status, "invalid")
            test.eq((over.findings :: { Map })[1].code, "links_limit")
            local peer = steps.one(h, { op = "link", item = a, type = "relates", target = { item = b } })
            test.eq(peer.status, "invalid")
            test.eq((peer.findings :: { Map })[1].code, "links_limit")
        end)

        test.it("refuses activating a relation rollup over a holder past the bound", function()
            local h = fixture.board({ declaration = declaration() })
            local p = steps.create(h, "child")
            local db = assert(store.open())
            assert(db:execute([[WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 2001)
                INSERT INTO kickside_work_link (board_id, from_id, type, to_board_id, to_id, at, seq)
                SELECT $1, $2, 'blocks', $1, 'seeded-' || CAST(n.i AS text), 'now', 1 FROM n]], { h.id, p }))
            db:release()
            local out, err = h.call("apply_schema", { declaration = {
                fields = { { code = "held", type = "rollup", form = "int", of = "blocks", fn = "count" } },
                item_types = { { id = "child", process = "work", parent_types = { "parent" }, fields = { "points", "cost", "title", "due", "priority", "symmetric", "held" } } },
            } })
            test.is_nil(out)
            test.eq((err:details() :: Map).code, "links_limit")
        end)
    end)
end

return { run = test.run_cases(define), declaration = declaration }
