local test = require("test")
local scoped = require("scoped")
local reconcile = require("reconcile")
local fixture = require("fixture")
local batch = require("batch")
local planner = require("planner")
local component = require("component")
local views = require("views")
local identifiers = require("identifiers")
local store = require("store")

local function define()
    test.describe("pack execution bounds", function()
        test.it("requires live ADMIN before a resumed view installation", function()
            assert(reconcile.trigger({ source = "pack_authority_test" }))
            local admin, member = scoped.admin(), scoped.member()
            local h = scoped.board(admin)
            assert(h.call("grant", { subject_id = member.id, mask = 3 }))
            local plan = assert(admin.call("pack_plan", { board_id = h.id, pack = "app:kanban_pack", expected_generation = 1 }))
            local _, err = member.call("pack_step", { board_id = h.id, operation_id = "resumed", actor_id = member.id,
                processed = 1, status = "running", counts = {}, data = { plan = plan, expected_generation = 1, starter = false } }, h.id)
            test.eq(#assert(h.call("list_views", {})).views, 0)
            test.not_nil(err)
            test.eq(err:kind(), errors.PERMISSION_DENIED)
        end)
        test.it("conflicts when a managed view changes after its reviewed revision", function()
            local h = fixture.board()
            local id = assert(h.call("create_view", { board_id = h.id, title = "View", view = { type = "list", columns = { "title" } } })).view_id
            local revision = assert(h.call("view_revision", { view_id = id }))
            assert(h.call("save_view", { view_id = id, view = { type = "list", columns = { "estimate" } } }))
            local _, err = h.call("pack_view", { view_id = id, revision = revision, request = { board_id = h.id, title = "Frozen", view = { type = "list", columns = { "labels" } } } })
            test.eq(assert(h.call("get_view", { view_id = id })).view.columns[1], "estimate")
            test.not_nil(err)
            test.eq(err:kind(), errors.CONFLICT)
        end)
        test.it("reconfigures a managed automation at its reviewed revision", function()
            local admin=scoped.admin()
            local created=assert(admin.call("create",{idempotency_key=fixture.fresh_prefix(),pack="app:kanban_pack",starter=false}))
            local target=scoped.board(admin)
            local plan=assert(admin.call("pack_plan",{board_id=created.board_id,pack="app:kanban_pack",expected_generation=1}))
            local entry=plan.automations[1]
            local id=assert(identifiers.resource(created.board_id,"automation",entry.id))
            entry.input.board_id=target.id
            local owner=assert(admin.call("pack_owner",{key="reviewed-upgrade",data={plan=plan,expected_generation=1,starter=false}},created.board_id))
            local db=assert(store.open())
            assert(db:execute("UPDATE kickside_work_operation SET processed=$1 WHERE board_id=$2 AND operation_id=$3",{1+#plan.views,created.board_id,owner.operation_id}));db:release()
            local done,err=admin.call("direct",{target="app:pack_run",input={operation_id=owner.operation_id,board_id=created.board_id}})
            test.is_nil(err,tostring(err));test.is_true(done)
            local context=assert(admin.call("attachment_context",{id=id}))
            test.eq(context._portable_input.board_id,target.id)
        end)
        test.it("conflicts without changing an automation after its reviewed revision is stale", function()
            local admin=scoped.admin()
            local created=assert(admin.call("create",{idempotency_key=fixture.fresh_prefix(),pack="app:kanban_pack",starter=false}))
            local target=scoped.board(admin)
            local plan=assert(admin.call("pack_plan",{board_id=created.board_id,pack="app:kanban_pack",expected_generation=1}))
            local entry=plan.automations[1]
            local id=assert(identifiers.resource(created.board_id,"automation",entry.id))
            assert(admin.call("automation_reconfigure",{id=id,input={board_id=target.id},revision=entry.revision}))
            entry.input.board_id=created.board_id
            local owner=assert(admin.call("pack_owner",{key="stale-upgrade",data={plan=plan,expected_generation=1,starter=false}},created.board_id))
            local db=assert(store.open())
            assert(db:execute("UPDATE kickside_work_operation SET processed=$1 WHERE board_id=$2 AND operation_id=$3",{1+#plan.views,created.board_id,owner.operation_id}))
            local before=assert(db:query("SELECT context_revision FROM kickside_components WHERE component_id=$1",{id}))[1].context_revision
            db:release()
            local _,err=admin.call("direct",{target="app:pack_run",input={operation_id=owner.operation_id,board_id=created.board_id}})
            test.not_nil(err);test.eq(err:kind(),errors.CONFLICT)
            local context=assert(admin.call("attachment_context",{id=id}))
            test.eq(context._portable_input.board_id,target.id)
            db=assert(store.open())
            test.eq(assert(db:query("SELECT context_revision FROM kickside_components WHERE component_id=$1",{id}))[1].context_revision,before)
            db:release()
        end)
        test.it("starts no resource effect after its enclosing deadline", function()
            local h = fixture.board()
            local plan = assert(h.call("pack_plan", { board_id = h.id, pack = "app:kanban_pack", expected_generation = 1 }))
            local before = assert(h.call("get_schema", {})).generation
            local done, err = h.call("pack_step", { board_id = h.id, operation_id = "expired", actor_id = h.actor:id(),
                processed = 0, status = "running", counts = {}, deadline = { at = "2000-01-01T00:00:00Z", ns = 0 },
                data = { plan = plan, expected_generation = 1, starter = false } })
            test.eq(assert(h.call("get_schema", {})).generation, before)
            test.is_nil(err, tostring(err))
            test.is_false(done)
        end)
    end)
end
return { run = test.run_cases(define) }
