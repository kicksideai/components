-- Edge cases of the small mechanisms: row narrowing, clock, bulk, shape, declaration
-- merge and the thread client's error paths.
local test = require("test")
local sql = require("sql")
local store = require("store")
local clock = require("clock")
local time = require("time")
local bulk = require("bulk")
local shape = require("shape")
local declaration = require("declaration")
local changes = require("changes")
local threads = require("threads")
local json = require("json")
local types = require("types")
local job_rows = require("job_rows")
local uuid = require("uuid")

type Map = { [string]: unknown }
type Named = { name: string }

local function db(): sql.DB
    local h, err = sql.get("app:db")
    assert(h, tostring(err))
    return h
end

local function client(overrides: Map): types.ThreadClient
    local c: Map = {}
    for k, v in pairs(overrides) do c[k] = v end
    local untyped: unknown = c
    return untyped :: types.ThreadClient
end

local function key(e: Named): string? return e.name end

local function define()
    test.describe("checked persistence boundaries", function()
        test.it("returns a corrupt required column as a native result error", function()
            local fake: unknown = { query = function(_self: unknown, _query: string, _args: unknown): (unknown, error?) return { { item_id = "i" } }, nil end }
            local value, err = store.item(fake :: sql.DB, "b", "i")
            test.is_nil(value)
            test.not_nil(err)
            test.eq(err:kind(), errors.INTERNAL)
            test.eq(err:details().code, "row_corrupt")
        end)
        test.it("preserves newer reindex and recompute demands on stale completion", function()
            local h = db()
            local tx = assert(h:begin())
            local board_id = uuid.v4()
            for _, kind in ipairs({ "reindex", "recompute" }) do
                assert(tx:execute("INSERT INTO kickside_work_job (board_id,job_id,job_type,key,status) VALUES ($1,$2,$3,'new','pending')", { board_id, "job-" .. kind, kind }))
                local done, err = job_rows.finish_rebuild(tx, board_id, "job-" .. kind, kind, "old")
                test.is_nil(err)
                test.is_false(done)
                local rows = assert(tx:query("SELECT key, status FROM kickside_work_job WHERE board_id = $1 AND job_id = $2", { board_id, "job-" .. kind }))
                test.eq(rows[1].key, "new")
                test.eq(rows[1].status, "pending")
            end
            assert(tx:rollback())
            h:release()
        end)
    end)

    test.describe("row narrowing", function()
        test.it("reads integers from numbers and numeric text", function()
            test.eq(store.int(5), 5)
            test.eq(store.int("5"), 5)
            test.eq(store.int(5.0), 5)
        end)
        test.it("refuses what is not an integer", function()
            test.is_nil(store.int(5.5))
            test.is_nil(store.int("x"))
            test.is_nil(store.int(nil))
            test.is_nil(store.int({}))
            test.is_nil(store.int(true))
        end)
        test.it("reads only strings as text", function()
            test.eq(store.text("a"), "a")
            test.eq(store.text(""), "")
            test.is_nil(store.text(5))
            test.is_nil(store.text(nil))
        end)
    end)

    test.describe("clock", function()
        test.it("writes canonical UTC timestamps that order as text", function()
            local now = clock.now()
            test.is_true(now:match("^%d%d%d%d%-%d%d%-%d%dT%d%d:%d%d:%d%d%.%d%d%d%d%d%d%d%d%dZ$") ~= nil)
            test.is_true(clock.offset(-86400) < now)
            test.is_true(clock.offset(-30 * 86400) < clock.offset(-86400))
        end)
        test.it("passes a deadline only after its instant", function()
            test.is_false(clock.passed(clock.deadline(60000)))
            test.is_true(clock.passed(clock.deadline(-1000)))
        end)
        test.it("keeps the exact command and read deadline in its serialized instant", function()
            local deadline = clock.deadline(5000)
            test.eq(#deadline.at, 30)
            test.is_true(deadline.at:match("^%d%d%d%d%-%d%d%-%d%dT") ~= nil)
            test.is_true(deadline.ns > 0)
            test.eq(assert(time.parse(time.RFC3339, deadline.at)):unix_nano(), deadline.ns)
        end)
    end)

    test.describe("bulk edges", function()
        local function fresh(h: sql.DB)
            assert(h:execute("DROP TABLE IF EXISTS bulk_edge", {}))
            assert(h:execute("CREATE TABLE bulk_edge (id TEXT PRIMARY KEY, note TEXT)", {}))
        end
        test.it("writes SQL NULL values", function()
            local h = db()
            fresh(h)
            test.is_nil(bulk.insert(h, "bulk_edge", { { name = "id" }, { name = "note" } }, { { "a", sql.NULL }, { "b", "x" } }))
            local rows = assert(h:query("SELECT id FROM bulk_edge WHERE note IS NULL", {}))
            test.eq(#rows, 1)
            test.eq(rows[1].id, "a")
            h:release()
        end)
        test.it("binds hostile values", function()
            local h = db()
            fresh(h)
            local hostile = "x'); DROP TABLE bulk_edge; --"
            test.is_nil(bulk.insert(h, "bulk_edge", { { name = "id" } }, { { hostile } }))
            test.is_nil(bulk.delete_in(h, "bulk_edge", nil, {}, "id", { hostile }))
            local rows = assert(h:query("SELECT COUNT(*) AS n FROM bulk_edge", {}))
            test.eq(store.int(rows[1].n), 0)
            h:release()
        end)
        test.it("answers a constraint failure as an error", function()
            local h = db()
            fresh(h)
            test.is_nil(bulk.insert(h, "bulk_edge", { { name = "id" } }, { { "a" } }))
            test.not_nil(bulk.insert(h, "bulk_edge", { { name = "id" } }, { { "a" } }))
            h:release()
        end)
        test.it("rolls back with its transaction", function()
            local h = db()
            fresh(h)
            local tx = assert(h:begin())
            test.is_nil(bulk.insert(tx, "bulk_edge", { { name = "id" } }, { { "a" }, { "b" } }))
            tx:rollback()
            local rows = assert(h:query("SELECT COUNT(*) AS n FROM bulk_edge", {}))
            test.eq(store.int(rows[1].n), 0)
            h:release()
        end)
    end)

    test.describe("shape edges", function()
        local function ok(schema: types.JsonObject, value: unknown) test.is_nil(shape.check(shape.tolerant(schema), value, "probe")) end
        local function bad(schema: types.JsonObject, value: unknown) test.not_nil(shape.check(shape.tolerant(schema), value, "probe")) end

        test.it("applies list rules inside nested lists and objects", function()
            local schema: types.JsonObject = { type = "array", items = { type = "object", required = { "n" }, properties = { n = { type = "array", items = { type = "integer" } } } } }
            ok(schema, { { n = { 1 } }, { n = {} } })
            bad(schema, { { n = { "x" } } })
            bad(schema, { {} })
        end)
        test.it("keeps minItems and required over an empty table", function()
            bad({ type = "array", minItems = 1 }, {})
            ok({ type = "array", minItems = 0 }, {})
            bad({ type = "object", required = { "a" } }, {})
            bad({ type = "object", minProperties = 1 }, {})
            bad({ type = "object", required = { "a" } }, json.decode("[]"))
            bad({ type = "array", minItems = 1 }, json.decode("{}"))
            ok({ type = "object", required = {} }, {})
        end)

        test.it("honours additionalProperties given as a schema", function()
            local schema: types.JsonObject = { type = "object", additionalProperties = { type = "array", items = { type = "string" } } }
            ok(schema, { a = {}, b = { "x" } })
            bad(schema, { a = { 1 } })
        end)
        test.it("keeps anyOf, enum and minimum working", function()
            ok({ anyOf = { { type = "string" }, { type = "array", items = { type = "integer" } } } }, {})
            ok({ enum = { "a", "b" } }, "a")
            bad({ enum = { "a", "b" } }, "c")
            bad({ type = "integer", minimum = 1 }, 0)
        end)
        test.it("reads boolean schemas", function()
            ok({ type = "object", properties = { x = true } }, { x = 5 })
            bad({ type = "object", properties = { x = false } }, { x = 5 })
        end)
        test.it("leaves scalars alone", function()
            ok({ type = "string" }, "x")
            bad({ type = "string" }, 5)
            bad({ type = "object" }, "x")
            bad({ type = "array" }, 5)
        end)
        test.it("treats non-empty values strictly", function()
            bad({ type = "array" }, { a = 1 })
            bad({ type = "object" }, { 1, 2 })
        end)
        test.it("accepts schemas decoded from JSON text", function()
            local decoded = json.decode('{"type":"object","properties":{"v":{},"list":{"type":"array"}},"required":["v"]}') :: types.JsonObject
            ok(decoded, { v = 1, list = {} })
            bad(decoded, { list = {} })
        end)
        test.it("names the value in its error", function()
            local err = shape.check(shape.tolerant({ type = "string" }), 5, "the probe")
            test.is_true(tostring(err):find("the probe", 1, true) ~= nil)
            test.eq((err :: error):kind(), errors.INVALID)
        end)
    end)

    test.describe("declaration merge edges", function()
        test.it("copies deeply", function()
            local source = { a = { b = { 1 } } }
            local copied = declaration.copy(source)
            copied.a.b[1] = 2
            test.eq(source.a.b[1], 1)
        end)
        test.it("keeps entries without a key out of a merge", function()
            local out = assert(declaration.merge_list({ { name = "a" } } :: { Named }, { {} :: Named }, key))
            test.eq(#out, 1)
        end)
        test.it("removes nothing for no names", function()
            test.eq(#assert(declaration.remove_from("x", { { name = "a" } } :: { Named }, nil, key)), 1)
            test.eq(#assert(declaration.remove_from("x", nil, nil, key)), 0)
        end)
        test.it("reports nothing between identical field sets", function()
            local f: types.Field = { id = 1, code = "a", type = "t", form = "text", cardinality = "one", index = "none", config = {}, track = false, intervals = false }
            test.eq(#changes.field_changes({ a = f }, { a = f }, { [1] = 3 }), 0)
        end)
    end)

    test.describe("thread client errors", function()
        test.it("reports a catch-up that finished without a position", function()
            local _, err = threads.catch_up(client({ catch_up_projection = function(_s: unknown, _r: unknown): (unknown, error?) return { done = true }, nil end }), "t", "k", clock.deadline(100))
            test.eq((err :: error):kind(), errors.INTERNAL)
        end)
        test.it("reports an unfinished catch-up without an error", function()
            local out, err = threads.catch_up(client({ catch_up_projection = function(_s: unknown, _r: unknown): (unknown, error?) return { done = false }, nil end }), "t", "k", clock.deadline(100))
            test.is_nil(err)
            test.is_false((out :: types.CatchUp).done)
        end)
        test.it("recognizes only conflicts of the named reason", function()
            local conflict = errors.new({ kind = errors.CONFLICT, message = "x", details = { reason = "head_mismatch" } })
            test.is_true(threads.mismatch(conflict, "head_mismatch"))
            test.is_false(threads.mismatch(conflict, "version_mismatch"))
            test.is_false(threads.mismatch(errors.new({ kind = errors.INTERNAL, message = "x", details = { reason = "head_mismatch" } }), "head_mismatch"))
        end)
        test.it("reports a marker body that is not JSON and a marker without a seq", function()
            local function with(event: Map): types.ThreadClient
                return client({ find_event_by_external = function(_s: unknown, _r: unknown): (unknown, error?) return { event = event }, nil end })
            end
            local _, bad = threads.find_marker(with({ seq = 1, body = "{broken" }), "t", "e", "s", "x")
            test.not_nil(bad)
            local _, noseq = threads.find_marker(with({ body = "{}" }), "t", "e", "s", "x")
            test.eq((noseq :: error):kind(), errors.INTERNAL)
            local found = assert(threads.find_marker(with({ seq = "7", body = '{"a":1}' }), "t", "e", "s", "x"))
            test.eq(found.seq, 7)
            test.eq((found.body :: Map).a, 1)
        end)
        test.it("answers no marker as nil", function()
            local c = client({ find_event_by_external = function(_s: unknown, _r: unknown): (unknown, error?) return {}, nil end })
            local found, err = threads.find_marker(c, "t", "e", "s", "x")
            test.is_nil(found)
            test.is_nil(err)
        end)
    end)
end

return { run = test.run_cases(define) }
