local row_checks = require("row_checks")
-- Change history, the changes feed, and fold idempotence under redelivery.
local test = require("test")
local json = require("json")
local fixture = require("fixture")
local steps = require("steps")
local store = require("store")
local materializer = require("materializer")

local function define()
    test.describe("list_history", function()
        test.it("records lifecycle rows and tracked value rows with before and after", function()
            local h = fixture.board()
            local id = steps.create(h, "story", { title = "A", estimate = 2, labels = { "x" } })
            steps.one(h, { op = "set", item = id, values = { title = "B", estimate = 3, labels = { "y" } } })
            steps.one(h, { op = "set", item = id, clear = { "estimate" } })
            steps.one(h, { op = "delete", item = id })
            steps.one(h, { op = "restore", item = id })
            local page = assert(h.call("list_history", { item = { id = id } }))
            local kinds = {}
            for _, e in ipairs(page.entries) do kinds[#kinds + 1] = e.kind .. (e.field and (":" .. e.field) or "") end
            test.eq(table.concat(kinds, ","), "restored,deleted,clear:estimate,set:title,set:estimate,set:title,set:estimate,created")
            local entries = page.entries
            test.eq(entries[3].before, 3)
            test.is_nil(entries[3].after)
            test.eq(entries[4].before, "A")
            test.eq(entries[4].after, "B")
            test.eq(entries[5].before, 2)
            test.eq(entries[5].after, 3)
            test.eq(entries[8].after.key, h.prefix .. "-1")
            test.eq(entries[1].actor, h.actor:id())
            test.eq(entries[1].source, "api")
            test.not_nil(entries[1].at)
        end)

        test.it("leaves untracked fields out of value rows and honours the audit policy", function()
            local h = fixture.board()
            local id = steps.create(h, "story", { title = "A", labels = { "x" } })
            steps.one(h, { op = "set", item = id, values = { labels = { "z" } } })
            local page = assert(h.call("list_history", { item = { id = id } }))
            test.eq(#page.entries, 2)
            local declaration = fixture.declaration(h.prefix)
            declaration.policy = { audit = "off" }
            assert(h.call("apply_schema", { declaration = declaration }))
            steps.one(h, { op = "set", item = id, values = { title = "off" } })
            local after = assert(h.call("list_history", { item = { id = id } }))
            test.eq(#after.entries, 2)
        end)

        test.it("pages board history newest first with a cursor", function()
            local h = fixture.board()
            for i = 1, 5 do steps.create(h, "task", { title = "T" .. i }) end
            local first = assert(h.call("list_history", { limit = 4 }))
            test.eq(#first.entries, 4)
            test.not_nil(first.next)
            test.eq(first.entries[1].kind, "set")
            local rest = assert(h.call("list_history", { limit = 50, before = first.next }))
            local last = rest.entries[#rest.entries]
            test.eq(last.kind, "schema")
            test.is_nil(rest.next)
            test.eq(#first.entries + #rest.entries, 11)
            local _, err = h.call("list_history", { before = "nonsense" })
            test.eq(err:kind(), errors.INVALID)
            local _, lerr = h.call("list_history", { limit = 0 })
            test.eq(lerr:kind(), errors.INVALID)
        end)

        test.it("writes subtree rows for a cascaded delete and restore", function()
            local h = fixture.board()
            local epic = steps.create(h, "epic", { title = "E" })
            local story = steps.create(h, "story", { title = "S" }, epic)
            steps.one(h, { op = "delete", item = epic })
            local page = assert(h.call("list_history", { item = { id = story } }))
            test.eq(page.entries[1].kind, "deleted")
            steps.one(h, { op = "restore", item = epic })
            page = assert(h.call("list_history", { item = { id = story } }))
            test.eq(page.entries[1].kind, "restored")
        end)
    end)

    test.describe("changes feed", function()
        test.it("pages items in update order from a cursor and reports trashed items as deletes", function()
            local h = fixture.board()
            local a = steps.create(h, "task", { title = "A" })
            local b = steps.create(h, "task", { title = "B" })
            local c = steps.create(h, "task", { title = "C" })
            local first = assert(h.call("list_changes", { limit = 2 }))
            test.eq(#first.items, 2)
            test.is_true(first.has_more)
            test.eq(first.items[1].item_id, a)
            test.eq(first.items[1].op, "upsert")
            test.eq(first.items[1].values.title, "A")
            test.eq(first.items[1].key, h.prefix .. "-1")
            local rest = assert(h.call("list_changes", { cursor = first.next, limit = 10 }))
            test.eq(#rest.items, 1)
            test.eq(rest.items[1].item_id, c)
            test.is_false(rest.has_more)
            steps.one(h, { op = "set", item = a, values = { title = "A2" } })
            steps.one(h, { op = "delete", item = b })
            local news = assert(h.call("list_changes", { cursor = rest.next }))
            test.eq(#news.items, 2)
            test.eq(news.items[1].item_id, a)
            test.eq(news.items[1].version, 2)
            test.eq(news.items[2].item_id, b)
            test.eq(news.items[2].op, "delete")
            test.is_nil(news.items[2].values)
            test.is_true(news.as_of >= news.items[2].updated_seq)
            local again = assert(h.call("list_changes", { cursor = news.next }))
            test.eq(#again.items, 0)
            test.eq(again.next.seq, news.next.seq)
        end)

        test.it("refuses a page size outside the limit", function()
            local h = fixture.board()
            local _, err = h.call("list_changes", { limit = 201 })
            test.eq(err:kind(), errors.INVALID)
        end)

        test.it("reports a source gap below the tombstone floor", function()
            local h = fixture.board()
            steps.create(h, "task", { title = "A" })
            local db = assert(store.open())
            assert(db:execute("UPDATE kickside_work_board SET tombstone_floor_seq = 100 WHERE board_id = $1", { h.id }))
            db:release()
            local page = assert(h.call("list_changes", { cursor = { seq = 5, item_id = "" } }))
            test.eq(page.gap.floor, 100)
            test.eq(#page.items, 0)
            test.eq(#assert(h.call("list_changes", {})).items, 1)
        end)

        test.it("requires the committed snapshot to cover min_seq", function()
            local h = fixture.board()
            local out = assert(steps.apply(h, { { op = "create", type = "task", values = { title = "A" } } }))
            local page = assert(h.call("list_changes", { min_seq = out.seq }))
            test.eq(#page.items, 1)
            local _, err = h.call("list_changes", { min_seq = (out.seq :: integer) + 1000 })
            test.eq(err:kind(), errors.UNAVAILABLE)
            test.eq(err:details().code, "projection_pending")
        end)
    end)

    test.describe("fold", function()
        test.it("treats a replayed projection batch as already folded and writes each change row once", function()
            local h = fixture.board()
            local epic = steps.create(h, "epic", { title = "E" })
            local story = steps.create(h, "story", { title = "S", estimate = 2 }, epic)
            steps.one(h, { op = "set", item = story, values = { estimate = 3 } })
            steps.one(h, { op = "link", item = story, type = "relates", target = { item = epic } })
            steps.one(h, { op = "comment", item = story, body = "hi" })
            steps.one(h, { op = "delete", item = epic })
            local page = assert(h.call("events", {}))
            local rows = page.events
            local db = assert(store.open())
            local items_before = assert(db:query("SELECT item_id, version, updated_seq, life FROM kickside_work_item WHERE board_id = $1 ORDER BY item_id", { h.id }))
            local changes_before = row_checks.scalar("SELECT COUNT(*) AS n FROM kickside_work_change WHERE board_id = $1", { h.id })
            local board_before = assert(store.board(db, h.id))
            local tx = assert(db:begin())
            local events = {}
            for _, r in ipairs(rows) do events[#events + 1] = { seq = r.seq, type = r.type, body = r.body } end
            local _, err = materializer.fold(tx, db:type(), h.id, events, math.tointeger(tonumber(rows[#rows].seq)) :: integer, 5000)
            test.is_nil(err)
            tx:commit()
            local items_after = assert(db:query("SELECT item_id, version, updated_seq, life FROM kickside_work_item WHERE board_id = $1 ORDER BY item_id", { h.id }))
            local board_after = assert(store.board(db, h.id))
            db:release()
            test.eq((json.encode(items_after)), (json.encode(items_before)))
            test.eq(row_checks.scalar("SELECT COUNT(*) AS n FROM kickside_work_change WHERE board_id = $1", { h.id }), changes_before)
            test.is_true(changes_before > 0)
            test.eq(board_after.counter, board_before.counter)
            test.eq(board_after.applied_seq, board_before.applied_seq)
        end)

        test.it("stops at its row budget and reports where", function()
            local h = fixture.board()
            local ops = {}
            for i = 1, 10 do ops[i] = { op = "create", type = "task", values = { title = "T" .. i } } end
            assert(steps.apply(h, ops))
            local page = assert(h.call("events", {}))
            local rows = page.events
            local db = assert(store.open())
            local tx = assert(db:begin())
            local events = {}
            for _, r in ipairs(rows) do
                local body = r.body
                if type(body) == "string" then body = json.decode(body) end
                if body.compiled then body.compiled.key_prefix = fixture.fresh_prefix() end
                events[#events + 1] = { seq = r.seq, type = r.type, body = body }
            end
            local folded, err = materializer.fold(tx, db:type(), (require("uuid").v4()), events, math.tointeger(tonumber(rows[#rows].seq)) :: integer, 3)
            tx:rollback()
            db:release()
            test.is_nil(err, steps.detail(err))
            test.eq(folded.last_seq, math.tointeger(tonumber(rows[2].seq)))
        end)
    end)
end

return { run = test.run_cases(define) }
