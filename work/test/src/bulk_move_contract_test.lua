            test.eq(operations.finished(h, start.bulk_id).status, "done")
            for _, event in ipairs(steps.events(h)) do
                if event.type == "kickside.work.events:bulk.progress" then
                    for _, name in ipairs({ "applied", "unchanged", "invalid", "denied", "conflict", "unavailable" }) do test.eq(type(event.body.counts[name]), "number") end
                    test.is_true(json.validate(assert(registry.get(event.type)).data.schema, event.body) == true)
                end
            end
        end)
        test.it("closes bulk progress counts and moved document patch schemas", function()
            local progress = assert(registry.get("kickside.work.events:bulk.progress")).data.schema
            local valid = { operation_id = "id", processed = 0, total = 1, status = "running", counts = { applied = 0 } }
            test.is_true(json.validate(progress, valid) == true)
            valid.counts.unrecognized = 1
            test.is_false(json.validate(progress, valid) == true)
            local incoming = assert(registry.get("kickside.work.events:item.moved_in")).data.schema
            local event = { item = "id", type = "task", state = "open", operation_id = "id", moved_from = { board = "b", item = "i" }, patch = { { f = 1, v = "text", unrecognized = true } } }
            test.is_false(json.validate(incoming, event) == true)
        end)
    end)
