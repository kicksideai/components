local originals = {}
local owned = {}
local function track(admin, id)
    owned[#owned + 1] = { admin = admin, id = id }
    return id
end
local function empty(admin)
    return track(admin, assert(admin.call("create", { idempotency_key = uuid.v4(), title = "Pack board" })).board_id)
end
local function install(admin, id, pack, starter, key)
    return admin.call("pack_apply", { board_id = id, pack = pack or "app:kanban_pack", expected_generation = 0,
        key = key or "install", starter = starter })
end
local function schema(admin, id)
    return assert(admin.call("get_schema", {}, id))
end
local function field(declaration, code)
    for _, value in ipairs(declaration.fields) do if value.code == code then return value end end
end
