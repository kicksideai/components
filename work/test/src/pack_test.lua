                expected[id] = true
            end
            local after, seen, pages = 0, {}, 0
            repeat
                local response = admin.http("GET", "/api/work/packs/boards?limit=1&after=" .. after)
                test.eq(response.status, 200, json.encode(response.body))
                local page = response.body.data
