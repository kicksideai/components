local test = require("test")
local fixture = require("fixture")
local steps = require("steps")
local store = require("store")

local function declaration(): { [string]: unknown }
    local d = fixture.declaration(fixture.fresh_prefix())
    d.plugins = { { use = "app:model_plugin" }, { use = "app:work_plugin" } }
    d.processes[1].states[2] = { id = "done", category = "completed" }
    d.processes[1].transitions = { { id = "finish", from = { "open" }, to = "done", guards = { "app:model_guard" } } }
    return d
end

local function define()
    test.describe("activated model seams", function()
        test.it("classifies added guards and invariants as semantic alongside label edits", function()
            local d = declaration()
            local h = fixture.board({ declaration = d })
            d.processes[1].states[1].name = "Renamed"
            d.processes[1].states[1].invariants = { "app:model_guard" }
            test.eq(assert(h.call("plan_schema", { declaration = d })).class, "semantic")
            d.processes[1].states[1].invariants = nil
            d.processes[1].transitions[1].name = "Renamed transition"
            d.processes[1].transitions[1].guards = { "app:model_group_guard" }
            test.eq(assert(h.call("plan_schema", { declaration = d })).class, "semantic")
        end)
        test.it("honors an exhaustion guard denial without explanatory findings", function()
            local d = declaration()
            d.processes[1].states[3] = { id = "build", category = "started", kind = "automated",
                run = { stage = "build", max_visits = 1, on_exhausted = "stop" } }
            d.processes[1].transitions = {
                { id = "start", from = { "open" }, to = "build" },
                { id = "back", from = { "build" }, to = "open" },
                { id = "stop", from = "any", to = "done", guards = { "app:model_guard" } },
            }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task", { estimate = 0 })
            test.eq(steps.one(h, { op = "transition", item = id, transition = "start" }).status, "applied")
            test.eq(steps.one(h, { op = "transition", item = id, transition = "back" }).status, "applied")
            local refused = steps.one(h, { op = "transition", item = id, transition = "start" })
            test.is_true(refused.status ~= "applied")
            test.eq(steps.get(h, id).item.state, "open")
        end)
        test.it("requires every declared plugin dependency before accepting activation", function()
            local h = fixture.board()
            local _, err = h.call("apply_schema", { declaration = { plugins = { { use = "app:model_plugin" } } } })
            test.not_nil(err)
            test.eq(err:kind(), errors.INVALID)
            test.eq(err:details().code, "plugin_required")
        end)
        test.it("requires both board activation and manifest membership for a guard", function()
            local h = fixture.board()
            local d = declaration()
            d.plugins = {}
            local _, err = h.call("apply_schema", { declaration = d })
            test.not_nil(err)
            test.eq(err:details().code, "plugin_seam_unowned")
            d.plugins = { { use = "app:model_plugin" }, { use = "app:work_plugin" } }
            d.processes[1].transitions[1].guards = { "app:unlisted_guard" }
            _, err = h.call("apply_schema", { declaration = d })
            test.not_nil(err)
            test.eq(err:details().code, "plugin_seam_unowned")
        end)
        test.it("runs transition guards as the caller for commands point reads and page reads", function()
            local h = fixture.board({ declaration = declaration() })
            local yes = steps.create(h, "task", { estimate = 2 })
            local no = steps.create(h, "task", { estimate = 1 })
            test.eq(#steps.get(h, yes, { "transitions" }).transitions, 1)
            test.eq(#steps.get(h, no, { "transitions" }).transitions, 0)
            local page = assert(h.call("query", { include = { "transitions" } }))
            for _, item in ipairs(page.items) do test.eq(#item.transitions, item.id == yes and 1 or 0) end
            local denied = steps.one(h, { op = "transition", item = no, transition = "finish" })
            test.eq(denied.status, "denied")
            test.eq(denied.findings[1].code, "estimate_required")
            test.eq(steps.one(h, { op = "transition", item = yes, transition = "finish" }).status, "applied")
        end)
        test.it("persists state invariant failures and outages as findings without stalling the fold", function()
            local d = declaration()
            d.processes[1].states[1].invariants = { "app:model_guard" }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task", { estimate = 1 })
            test.eq(steps.get(h, id).item.findings[1].code, "estimate_required")
            test.eq(steps.one(h, { op = "set", item = id, values = { estimate = -1 } }).status, "applied")
            test.eq(steps.get(h, id).item.findings[1].code, "guard_unavailable")
            test.eq(steps.one(h, { op = "set", item = id, values = { estimate = 2 } }).status, "applied")
            test.eq(#steps.get(h, id).item.findings, 0)
        end)
        test.it("supplies live caller groups to a guard without field or visibility restrictions", function()
            local d = declaration()
            d.processes[1].transitions[1].guards = { "app:model_group_guard" }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task", { estimate = 2 })
            test.eq(#assert(steps.get(h, id, { "transitions" })).transitions, 1)
            local db = assert(store.open())
            assert(db:execute("DELETE FROM app_user_groups WHERE user_id=$1 AND group_id=$2", { h.actor:id(), "app.security:work_test" }))
            db:release()
            test.eq(#steps.get(h, id, { "transitions" }).transitions, 0)
            local denied = steps.one(h, { op = "transition", item = id, transition = "finish" })
            test.eq(denied.status, "denied")
            test.eq(denied.findings[1].code, "model_group_required")
        end)
        test.it("supplies the board execution identity's groups to state invariant checks", function()
            local d = declaration()
            d.processes[1].states[1].invariants = { "app:model_group_guard" }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task", { estimate = 2 })
            test.eq(#steps.get(h, id).item.findings, 0)
        end)
        test.it("denies a guard's declared private input under the caller's field access", function()
            local d = declaration()
            d.fields[2].access = { read = { { group = "app.security:work_admin" } } }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task", { estimate = 2 })
            local call, member = fixture.user(h, nil, true)
            assert(h.call("grant", { subject_id = member, mask = 3 }))
            test.is_nil(assert(call("get", { item = { id = id } })).item.values.estimate)
            local _, err = call("get", { item = { id = id }, include = { "transitions" } })
            test.not_nil(err)
            test.eq(err:kind(), errors.PERMISSION_DENIED)
            test.eq(err:details().code, "field_denied")
            local result = assert(call("apply", { ops = { { op = "transition", item = id, transition = "finish" } } }))
            test.eq(result.outcomes[1].status, "denied")
            test.eq(result.outcomes[1].findings[1].code, "field_denied")
        end)
        test.it("resolves bounded named operands through the activated caller seam", function()
            local d = declaration()
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task", { estimate = 2 })
            steps.create(h, "task", { estimate = 3 })
            local page = assert(h.call("query", { where = { field = "estimate", op = "in", value = { ["$operand"] = { id = "app:model_operand", config = { value = 2 } } } } }))
            test.eq(#page.items, 1)
            test.eq(page.items[1].id, id)
            local unactivated = fixture.board()
            local _, err = unactivated.call("query", { where = { field = "estimate", op = "eq", value = { ["$operand"] = { id = "app:model_operand" } } } })
            test.not_nil(err)
            test.eq(err:details().code, "plugin_seam_unowned")
        end)
        test.it("resolves a scalar named operand through the field's ordinary form", function()
            local h = fixture.board({ declaration = declaration() })
            local id = steps.create(h, "task", { estimate = 2 })
            steps.create(h, "task", { estimate = 3 })
            local page = assert(h.call("query", { where = { field = "estimate", op = "eq",
                value = { ["$operand"] = { id = "app:model_operand", config = { value = 2, scalar = true } } } } }))
            test.eq(#page.items, 1)
            test.eq(page.items[1].id, id)
        end)
        test.it("returns a native error when a guard returns findings outside the declared list shape", function()
            local h = fixture.board({ declaration = declaration() })
            local id = steps.create(h, "task", { estimate = 1000 })
            local _, err = h.call("get", { item = { id = id }, include = { "transitions" } })
            test.not_nil(err)
            test.eq(err:kind(), errors.UNAVAILABLE)
            test.eq(err:details().code, "guard_result_invalid")
        end)
        test.it("searches activated match columns through the shared predicate language", function()
            local d = declaration()
            d.scopes = { "app:model_search" }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task")
            test.eq(#assert(h.call("query", { where = { match = id } })).items, 1)
            test.eq(#assert(h.call("query", { where = { ["not"] = { match = id } } })).items, 0)
            test.eq(#assert(h.call("query", { where = { match = "no such item" } })).items, 0)
            local plain = fixture.board()
            local _, err = plain.call("query", { where = { match = id } })
            test.eq(err:details().code, "search_unavailable")
            _, err = plain.call("apply_schema", { declaration = { scopes = { "app:model_search" } } })
            test.eq(err:details().code, "plugin_seam_in_use")
        end)
        test.it("enforces a resolver search scope's declared board access", function()
            local d = declaration()
            d.scopes = { "app:model_search_admin_ids" }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task")
            test.eq(#assert(h.call("query", { where = { match = id } })).items, 1)
            local call, actor = fixture.user(h, nil, true)
            assert(h.call("grant", { subject_id = actor, mask = 1 }))
            test.eq(#assert(call("query", {})).items, 1)
            local _, err = call("query", { where = { match = id } })
            test.not_nil(err)
            test.eq(err:kind(), errors.PERMISSION_DENIED)
            test.eq(err:details().code, "scope_access_denied")
        end)
        test.it("resolves search ids as the caller and intersects ordinary predicates", function()
            local d = declaration()
            d.scopes = { "app:model_search_ids" }
            local h = fixture.board({ declaration = d })
            local id = steps.create(h, "task", { estimate = 2 })
            steps.create(h, "task", { estimate = 3 })
            local page = assert(h.call("query", { where = { ["and"] = { { match = id }, { field = "estimate", op = "eq", value = 2 } } } }))
            test.eq(#page.items, 1)
            test.eq(page.items[1].id, id)
            test.eq(#assert(h.call("query", { where = { ["and"] = { { match = id }, { field = "estimate", op = "eq", value = 3 } } } })).items, 0)
            local _, err = h.call("query", { where = { match = "unavailable" } })
            test.eq(err:kind(), errors.UNAVAILABLE)
            test.eq(err:details().code, "search_offline")
        end)
    end)
end
return { run = test.run_cases(define) }
