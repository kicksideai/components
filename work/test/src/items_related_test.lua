-- Relations, comments, item lifecycle and reads through the apply and read paths.
local test = require("test")
local fixture = require("fixture")
local steps = require("steps")
local store = require("store")

local function board_row(h: fixture.Handle): { [string]: unknown }
    for _, board in ipairs(assert(h.call("list", {})).boards) do
        if board.board_id == h.id then return board end
    end
    error("board is absent from discovery")
end

local function define()
    test.describe("working relation cardinality", function()
        test.it("counts earlier links and unlinks in the same command", function()
            local h = fixture.board()
            local a, b, c = steps.create(h, "task"), steps.create(h, "task"), steps.create(h, "task")
            local out = assert(steps.apply(h, { { op = "link", item = a, type = "duplicates", target = { item = b } },
                { op = "link", item = a, type = "duplicates", target = { item = c } } }))
            test.is_false(out.applied)
            test.eq(out.outcomes[2].findings[1].code, "relation_cardinality")
            test.eq(steps.one(h, { op = "link", item = a, type = "duplicates", target = { item = b } }).status, "applied")
            out = assert(steps.apply(h, { { op = "unlink", item = a, type = "duplicates", target = { item = b } },
                { op = "link", item = a, type = "duplicates", target = { item = c } } }))
            test.is_true(out.applied)
        end)
    end)

    test.describe("relations", function()
        test.it("links and unlinks, and reads both directions", function()
            local h = fixture.board()
            local a = steps.create(h, "task", { title = "A" })
            local b = steps.create(h, "task", { title = "B" })
            local linked = steps.one(h, { op = "link", item = a, type = "blocks", target = { item = b } })
            test.eq(linked.status, "applied")
            test.eq(linked.version, 2)
            local from = assert(steps.get(h, a, { "links" })).links
            test.eq(#from, 1)
            test.eq(from[1].direction, "outward")
            test.eq(from[1].item, b)
            local to = assert(steps.get(h, b, { "links" })).links
            test.eq(#to, 1)
            test.eq(to[1].direction, "inward")
            test.eq(to[1].item, a)
            test.eq(steps.one(h, { op = "link", item = a, type = "blocks", target = { item = b } }).status, "unchanged")
            local unlinked = steps.one(h, { op = "unlink", item = a, type = "blocks", target = { item = b } })
            test.eq(unlinked.status, "applied")
            test.eq(#assert(steps.get(h, a, { "links" })).links, 0)
            test.eq(steps.one(h, { op = "unlink", item = a, type = "blocks", target = { item = b } }).status, "unchanged")
        end)

        test.it("stores a symmetric relation once and reads it from both items", function()
            local h = fixture.board()
            local a = steps.create(h, "task", { title = "A" })
            local b = steps.create(h, "task", { title = "B" })
            steps.one(h, { op = "link", item = b, type = "relates", target = { item = a } })
            test.eq(steps.one(h, { op = "link", item = a, type = "relates", target = { item = b } }).status, "unchanged")
            local db = assert(store.open())
            local rows = assert(db:query("SELECT * FROM kickside_work_link WHERE board_id = $1", { h.id }))
            db:release()
            test.eq(#rows, 1)
            test.eq(#assert(steps.get(h, a, { "links" })).links, 1)
            test.eq(#assert(steps.get(h, b, { "links" })).links, 1)
            test.eq(steps.one(h, { op = "unlink", item = a, type = "relates", target = { item = b } }).status, "applied")
            test.eq(#assert(steps.get(h, b, { "links" })).links, 0)
        end)

        test.it("enforces relation cardinality and validates targets", function()
            local h = fixture.board()
            local a = steps.create(h, "task", { title = "A" })
            local b = steps.create(h, "task", { title = "B" })
            local c = steps.create(h, "task", { title = "C" })
            steps.one(h, { op = "link", item = a, type = "duplicates", target = { item = b } })
            test.eq(steps.one(h, { op = "link", item = a, type = "duplicates", target = { item = c } }).findings[1].code, "relation_cardinality")
            test.eq(steps.one(h, { op = "link", item = a, type = "ghost", target = { item = b } }).findings[1].code, "unknown_relation")
            test.eq(steps.one(h, { op = "link", item = a, type = "blocks", target = { item = a } }).findings[1].code, "invalid_target")
            test.eq(steps.one(h, { op = "link", item = a, type = "blocks", target = { item = "00000000-0000-0000-0000-000000000000" } }).findings[1].code, "unknown_target")
            test.eq(steps.one(h, { op = "link", item = a, type = "blocks", target = { kind = "deal", id = "d1" } }).findings[1].code, "invalid_target")
            local out = assert(steps.apply(h, {
                { op = "link", item = a, type = "blocks", target = { item = b } },
                { op = "link", item = a, type = "blocks", target = { item = b } },
            }))
            test.eq(out.outcomes[1].status, "applied")
            test.eq(out.outcomes[2].status, "unchanged")
        end)

        test.it("links across boards only for a reader of the target board", function()
            local h = fixture.board()
            local other = fixture.board()
            local mine = steps.create(h, "task", { title = "mine" })
            local theirs = steps.create(other, "task", { title = "theirs" })
            local denied = steps.one(h, { op = "link", item = mine, type = "blocks", target = { board = other.id, item = theirs } })
            test.eq(denied.status, "denied")
            assert(other.call("grant", { subject_id = h.actor:id(), mask = 1 }))
            local ok = steps.one(h, { op = "link", item = mine, type = "blocks", target = { board = other.id, item = theirs } })
            test.eq(ok.status, "applied")
            local links = assert(steps.get(h, mine, { "links" })).links
            test.eq(links[1].board, other.id)
            test.eq(#assert(steps.get(other, theirs, { "links" })).links, 1)
        end)
    end)

    test.describe("comments", function()
        test.it("adds, edits and deletes comments without touching the item version", function()
            local h = fixture.board()
            local id = steps.create(h, "task", { title = "A" })
            local added = steps.one(h, { op = "comment", item = id, body = "first" })
            test.eq(added.status, "applied")
            test.not_nil(added.comment)
            test.eq(steps.version(h, id), 1)
            local comments = assert(steps.get(h, id, { "comments" })).comments
            test.eq(#comments, 1)
            test.eq(comments[1].body, "first")
            test.eq(comments[1].author, h.actor:id())
            test.eq(comments[1].version, 1)
            local edited = steps.one(h, { op = "comment", item = id, comment = added.comment, body = "second" })
            test.eq(edited.status, "applied")
            comments = assert(steps.get(h, id, { "comments" })).comments
            test.eq(comments[1].body, "second")
            test.eq(comments[1].version, 2)
            test.not_nil(comments[1].edited_at)
            test.eq(steps.one(h, { op = "comment", item = id, comment = added.comment, body = "second" }).status, "unchanged")
            test.eq(steps.one(h, { op = "comment", item = id, comment = added.comment, delete = true }).status, "applied")
            test.eq(#assert(steps.get(h, id, { "comments" })).comments, 0)
            test.eq(steps.one(h, { op = "comment", item = id, comment = added.comment, body = "late" }).findings[1].code, "unknown_comment")
        end)

        test.it("refuses empty bodies, foreign comments and trashed items", function()
            local h = fixture.board()
            local a = steps.create(h, "task", { title = "A" })
            local b = steps.create(h, "task", { title = "B" })
            test.eq(steps.one(h, { op = "comment", item = a, body = "" }).findings[1].code, "invalid_body")
            local c = steps.one(h, { op = "comment", item = a, body = "on a" })
            test.eq(steps.one(h, { op = "comment", item = b, comment = c.comment, body = "x" }).findings[1].code, "unknown_comment")
            steps.one(h, { op = "delete", item = a })
            test.eq(steps.one(h, { op = "comment", item = a, body = "late" }).findings[1].code, "item_trashed")
        end)
    end)

    test.describe("delete and restore", function()
        test.it("trashes an item with its subtree, keeps discovery counts exact and restores what the delete moved", function()
            local h = fixture.board()
            local epic = steps.create(h, "epic", { title = "E" })
            local s1 = steps.create(h, "story", { title = "S1" }, epic)
            local s2 = steps.create(h, "story", { title = "S2" }, epic)
            local task = steps.create(h, "task", { title = "T" }, s1)
            test.eq(board_row(h).item_count, 4)
            test.eq(steps.one(h, { op = "delete", item = s2 }).status, "applied")
            test.eq(board_row(h).item_count, 3)
            test.eq(board_row(h).trashed_count, 1)
            local out = steps.one(h, { op = "delete", item = epic })
            test.eq(out.status, "applied")
            test.eq(out.version, 2)
            local row = board_row(h)
            test.eq(row.item_count, 0)
            test.eq(row.trashed_count, 4)
            test.eq(row.open_count, 0)
            test.eq(assert(steps.get(h, task)).item.life, "trashed")
            test.eq(steps.one(h, { op = "delete", item = epic }).status, "unchanged")
            local restored = steps.one(h, { op = "restore", item = epic })
            test.eq(restored.status, "applied")
            test.eq(restored.version, 3)
            test.eq(assert(steps.get(h, epic)).item.life, "live")
            test.eq(assert(steps.get(h, s1)).item.life, "live")
            test.eq(assert(steps.get(h, task)).item.life, "live")
            test.eq(assert(steps.get(h, s2)).item.life, "trashed")
            row = board_row(h)
            test.eq(row.item_count, 3)
            test.eq(row.trashed_count, 1)
            test.eq(row.open_count, 3)
            test.eq(steps.one(h, { op = "restore", item = epic }).status, "unchanged")
        end)

        test.it("restores a child only after its parent", function()
            local h = fixture.board()
            local epic = steps.create(h, "epic", { title = "E" })
            local story = steps.create(h, "story", { title = "S" }, epic)
            steps.one(h, { op = "delete", item = story })
            steps.one(h, { op = "delete", item = epic })
            local early = steps.one(h, { op = "restore", item = story })
            test.eq(early.findings[1].code, "parent_trashed")
            steps.one(h, { op = "restore", item = epic })
            test.eq(assert(steps.get(h, story)).item.life, "trashed")
            test.eq(steps.one(h, { op = "restore", item = story }).status, "applied")
            test.eq(assert(steps.get(h, story)).item.life, "live")
        end)

        test.it("needs delete access", function()
            local h = fixture.board()
            local id = steps.create(h, "task", { title = "A" })
            local writer, writer_id = fixture.user(h)
            assert(h.call("grant", { subject_id = writer_id, mask = 3 }))
            local out = assert(writer("apply", { ops = { { op = "delete", item = id } } }))
            test.eq(out.outcomes[1].status, "denied")
            test.eq(assert(steps.get(h, id)).item.life, "live")
            local deleter, deleter_id = fixture.user(h)
            assert(h.call("grant", { subject_id = deleter_id, mask = 7 }))
            local ok = assert(deleter("apply", { ops = { { op = "delete", item = id } } }))
            test.eq(ok.outcomes[1].status, "applied")
        end)
    end)

    test.describe("reads", function()
        test.it("refuses an unknown item and an ambiguous reference", function()
            local h = fixture.board()
            local _, e1 = h.call("get", { item = { id = "00000000-0000-0000-0000-000000000000" } })
            test.eq(e1:kind(), errors.NOT_FOUND)
            local _, e2 = h.call("get", { item = {} })
            test.eq(e2:kind(), errors.INVALID)
        end)

        test.it("resolves old keys after a prefix rename", function()
            local h = fixture.board()
            local id = steps.create(h, "task", { title = "A" })
            local old = h.prefix .. "-1"
            local fresh = fixture.fresh_prefix()
            local declaration = fixture.declaration(fresh)
            local plan = assert(h.call("plan_schema", { declaration = declaration }))
            test.eq(plan.class, "semantic")
            assert(h.call("apply_schema", { declaration = declaration }))
            local item = assert(steps.get(h, id)).item
            test.eq(item.key, fresh .. "-1")
            test.eq(assert(h.call("get", { item = { key = old } })).item.id, id)
            test.eq(assert(h.call("get", { item = { key = fresh .. "-1" } })).item.id, id)
            local next_id = steps.create(h, "task", { title = "B" })
            test.eq(assert(steps.get(h, next_id)).item.key, fresh .. "-2")
            local other = fixture.board({ bare = true })
            local taken = fixture.declaration(h.prefix)
            local _, err = other.call("apply_schema", { declaration = taken })
            test.not_nil(err)
            test.eq(err:details().code, "key_prefix_taken")
        end)
    end)
end

return { run = test.run_cases(define) }
