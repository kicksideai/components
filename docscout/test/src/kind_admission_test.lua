local test = require("test")
local contract = require("contract")
local security = require("security")
local funcs = require("funcs")
local registry = require("registry")
local json = require("json")
local uuid = require("uuid")
local data = require("data")
local KIND = "kickside.docscout:extractor"
local function scope()
    return assert(security.new_scope({assert(security.policy("app:kind_member"))}))
end
local function service(actor)
    return assert(contract.get("kickside.component:component_service")):with_actor(actor):with_scope(scope()):open()
end
local function denied(result, err)
    test.is_nil(err)
    test.is_false(result.success)
    test.eq(result.kind, errors.PERMISSION_DENIED)
    test.eq(result.details.code, "component_kind_mutation_denied")
end
return {run = test.run_cases(function()
    test.describe("extractor admission authority", function()
        test.it("requires owning admission for creation and every generic mutation", function()
            local actor = assert(security.new_actor(uuid.v4(), {}))
            local client = service(actor)
            denied(client:register({impl_id=KIND,private_context={config={fields={}}}}))
            local caller = funcs.new():with_actor(actor):with_scope(scope())
            local config = assert(json.decode(assert(registry.get("kickside.docscout:config_schema")).data.schema_json)).default
            local created, create_err = caller:call("app:probe",{op="create",input={title="Validated reader",config=config}})
            test.is_nil(create_err);test.not_nil(created)
            local id = created.component_id
            denied(client:update({component_id=id,commands={{type="PATCH_CONTEXT",payload={patch={config={fields={}}}}}}}))
            denied(client:set_meta({component_id=id,fields={title="Unvalidated"}}))
            denied(client:set_placement({component_id=id,position="z"}))
            local changed, change_err = caller:call("kickside.docscout.traits:configure_tool",{extractor_id=id,title="Updated reader",config=config,expected_revision=0})
            test.is_nil(change_err);test.is_true(changed.success)
            local saved = assert(caller:call("app:probe",{op="get",id=id}))
            test.eq(saved.title,"Updated reader");test.eq(saved.expected_revision,1)
            local invalid, invalid_err = caller:call("kickside.docscout.traits:configure_tool",{extractor_id=id,title="Invalid reader",config={fields={}},expected_revision=1})
            test.is_nil(invalid);test.not_nil(invalid_err);test.is_true(errors.is(invalid_err,errors.INVALID))
            test.eq(assert(caller:call("app:probe",{op="get",id=id})).expected_revision,1)
            local stranger = funcs.new():with_actor(assert(security.new_actor(uuid.v4(),{}))):with_scope(scope())
            local forbidden, forbidden_err = stranger:call("kickside.docscout.traits:configure_tool",{extractor_id=id,title="Stranger",config=config,expected_revision=1})
            test.is_nil(forbidden);test.is_true(errors.is(forbidden_err,errors.PERMISSION_DENIED))
            test.not_nil(assert(caller:call("app:probe",{op="delete",id=id})))
            data.await_delete(id)
        end)
    end)
end)}
