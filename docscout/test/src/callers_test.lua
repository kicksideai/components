local test = require("test")
local funcs = require("funcs")
local security = require("security")
local registry = require("registry")
local json = require("json")
local uuid = require("uuid")
local function scope() return security.new_scope({ assert(security.policy("app:user")) }) end
local function caller(id: string) return funcs.new():with_actor(security.new_actor(id, { security_groups = {} })):with_scope(scope()) end
local function defaults() return assert(json.decode(assert(registry.get("kickside.docscout:config_schema")).data.schema_json)).default end

return { run = test.run_cases(function()
    test.describe("Docscout callers", function()
        test.it("lists extractors with a filter, reads configuration with its schema and saves with a revision check", function()
            local who = "caller-" .. uuid.v4()
            local a = assert(caller(who):call("app:probe", { op = "create", input = { title = "Invoice reader", description = "", config = defaults() } }))
            assert(caller(who):call("app:probe", { op = "create", input = { title = "Contract reader", description = "", config = defaults() } }))
            local listed = assert(caller(who):call("kickside.docscout.callers:list_tool", { filter = "invoice" }))
            test.is_true(listed.success); test.eq(#listed.extractors, 1); test.eq(listed.extractors[1].title, "Invoice reader")
            local got = assert(caller(who):call("kickside.docscout.callers:get_tool", { extractor_id = a.component_id }))
            test.is_true(got.success); test.eq(got.expected_revision, 0)
            test.not_nil(got.config_schema.properties.stages)
            got.config.stages.scout.max_rounds = 3
            local saved = assert(caller(who):call("kickside.docscout.callers:configure_tool", { extractor_id = a.component_id, title = "Invoice reader", config = got.config, expected_revision = 0 }))
            test.is_true(saved.success, tostring(saved.error))
            local stale = assert(caller(who):call("kickside.docscout.callers:configure_tool", { extractor_id = a.component_id, title = "Invoice reader", config = got.config, expected_revision = 0 }))
            test.is_false(stale.success)
            local bad = assert(caller(who):call("kickside.docscout.callers:configure_tool", { extractor_id = a.component_id, title = "Invoice reader", config = { fields = {} }, expected_revision = 1 }))
            test.is_false(bad.success)
            local stranger = assert(caller("stranger-" .. uuid.v4()):call("kickside.docscout.callers:get_tool", { extractor_id = a.component_id }))
            test.is_false(stranger.success)
        end)
        test.it("refuses a Block run without an extractor or an upload", function()
            local who = "caller-" .. uuid.v4()
            local _, no_extractor = caller(who):call("kickside.docscout.callers:block_run", { config = {}, input = { upload_id = "u" } })
            test.not_nil(no_extractor)
            local _, no_upload = caller(who):call("kickside.docscout.callers:block_run", { config = { extractor_id = "x" }, input = {} })
            test.not_nil(no_upload)
            local block = assert(registry.get("kickside.docscout.callers:block.extract"))
            test.eq(block.data.block.execution.function_id, "kickside.docscout.callers:block_run")
            test.eq(block.data.block.config.properties.extractor_id.class, "kickside.docscout")
        end)
    end)
end) }
